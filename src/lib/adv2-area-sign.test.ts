/**
 * RED-TEAM РАУНД 2: знак минуса в parseArea.
 *
 * БЫЛО: раунд 1 добавил `(?<!-)` перед числом, и просмотр смотрел РОВНО на один
 * символ перед цифрой, поэтому:
 *  - любой другой знак минуса (U+2212, U+2013) и минус через пробел проходили;
 *  - многозначное число не отбрасывалось, а ОБРЕЗАЛОСЬ: движок сдвигал старт
 *    на одну цифру вправо и матчил хвост («-12 rai» → 2 rai);
 *  - «-800 m2» давало areaSqm = 0 (совпал хвост «00»), то есть площадь не просто
 *    неверна, а обнулена — до фикса там было честное 800.
 *
 * ИСПРАВЛЕНО 2026-08-31: `(?<!-)` убран, вместо него ранний выход
 * `if (/[-−–—]\s*\d/.test(s)) return {}` — минус любой формы, в том числе через
 * пробел, отклоняет ВЕСЬ ввод. Отрицательная площадь не превращается ни в
 * усечённое число, ни в ноль: поля просто не заполняются.
 *
 * Тесты стерегут фикс.
 *   npx tsx --test src/lib/adv2-*.test.ts
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { parseArea } from "./write";

// АТАКА 25 [MEDIUM]: юникод-минус и минус через пробел
// | ИНВАРИАНТ: «−5 rai» / «–5 rai» / «- 5 rai» отбрасываются так же, как «-5 rai»
// | код: backend/src/lib/write.ts:219-222
test("АТАКА 25: минус в юникоде и через пробел не проносит отрицательную площадь", () => {
  assert.deepEqual(parseArea("-5 rai"), {});
  assert.deepEqual(parseArea("−5 rai"), {}); // U+2212 minus
  assert.deepEqual(parseArea("–5 rai"), {}); // en dash
  assert.deepEqual(parseArea("—5 rai"), {}); // em dash
  assert.deepEqual(parseArea("- 5 rai"), {}); // минус через пробел
});

// АТАКА 25a [HIGH]: многозначное отрицательное число не обрезается до хвоста
// | ИНВАРИАНТ: «-12 rai» не распознаётся вовсе — ни 12, ни 2; иначе заниженная
//   площадь уехала бы в каталог, в оценку и в цену за рай
// | код: backend/src/lib/write.ts:222
test("АТАКА 25a: «-12 rai» не превращается в 2 rai", () => {
  assert.deepEqual(parseArea("-12 rai"), {});
  assert.deepEqual(parseArea("-1600 m2"), {});
});

// АТАКА 25b [HIGH]: регрессия «площадь 0» закрыта
// | ИНВАРИАНТ: «-800 m2» не даёт ни 0, ни 800 — ноль проходил дальнейшие проверки
//   как «площадь известна»: детектор полноты карточки видел заполненное поле,
//   а сайт печатал «0 m²»
// | код: backend/src/lib/write.ts:222,232-235
test("АТАКА 25b: «-800 m2» не записывает площадь 0", () => {
  assert.deepEqual(parseArea("-800 m2"), {});
  assert.deepEqual(parseArea("- 800 m2"), {});
  // контроль: без минуса площадь читается как раньше
  assert.deepEqual(parseArea("800 m2"), { sqm: 800, rai: 0.5 });
});

// АТАКА 25c [MEDIUM]: НЕ ЗАКРЫТО — десятичная запятая в квадратных метрах умножает на 10
// | ОЖИДАЕТСЯ: «1,5 m²» = 1.5 m² (для rai запятая обрабатывается верно —
//   replace(",", "."))
// | ФАКТ: ветка sqm вместо этого вырезает запятую как разделитель тысяч
//   → 15 m²; две ветки одной функции трактуют запятую по-разному
// | код: backend/src/lib/write.ts:230 vs :233
test("АТАКА 25c: «1,5 m²» читается как 15 m², а «1,5 rai» — как 1.5 rai", () => {
  assert.deepEqual(parseArea("1,5 m2"), { sqm: 15, rai: 0.01 });
  assert.deepEqual(parseArea("1,5 rai"), { sqm: 2400, rai: 1.5 });
});

// АТАКА 25d [MEDIUM]: частично отрицательный ввод не даёт «правдоподобного» мусора
// | ИНВАРИАНТ: «-3 rai 2 ngan» не даёт площадь вообще (раньше отбрасывалась
//   только часть, остальное складывалось в 0.5 rai)
// | код: backend/src/lib/write.ts:219-241
test("АТАКА 25d: «-3 rai 2 ngan» не складывается в 0.5 rai", () => {
  assert.deepEqual(parseArea("-3 rai 2 ngan"), {});
  // контроль: тот же ввод без минуса считается полностью
  assert.deepEqual(parseArea("3 rai 2 ngan"), { sqm: 5600, rai: 3.5 });
});
