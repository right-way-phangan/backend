/**
 * RED-TEAM РАУНД 2: фикс утечки descriptionRaw принёс ReDoS на путь записи.
 *
 * БЫЛО: раунд 1 поставил redactConfidential() в buildRow. Внутри неё описание
 * построчно прогонялось через CONTACT_LINE_RE, где жила почтовая альтернатива
 * `[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}`: классы по обе стороны от `@`
 * пересекаются по точке, поэтому на строке без валидного домена движок
 * перебирал разбиения квадратично. Длина входа не ограничивалась ничем
 * (DESC_MAX=500 применяется ПОСЛЕ и только при публикации), так что 64 000
 * символов в теле POST /objects занимали event loop серверлесс-функции на
 * минуту → таймаут вместо созданного объекта.
 *
 * ИСПРАВЛЕНО 2026-08-31: почтовый паттерн переписан с ограниченными сверху
 * квантификаторами (`{1,64}@{1,63}(?:\.{1,63}){1,4}`), а вход обрезается до
 * `MAX_SCAN_CHARS = 20 000` с предупреждением. Стоимость вызова теперь
 * ОГРАНИЧЕНА СВЕРХУ независимо от размера тела запроса.
 *
 * 26c остаётся ХАРАКТЕРИЗУЮЩИМ: под отсечкой рост всё ещё сверхлинейный.
 *
 * ИЗМЕРЕНИЯ 2026-09-01: 26, 26a и 26c мигали в полном прогоне — `node --test`
 * запускает файлы параллельно, и абсолютные миллисекунды на загруженной машине
 * растут в 5–10 раз. Все три переведены на ОТНОСИТЕЛЬНЫЕ величины, снятые в
 * том же процессе и вперемешку с измеряемым вызовом: скорость машины сокращается
 * в числителе и знаменателе, а инвариант («потолок есть», «рост не
 * катастрофический») сохраняется.
 *   npx tsx --test src/lib/adv2-*.test.ts
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { redactConfidential } from "./publishable";

/** Строка-ловушка: длинный локальный кусок, «@», длинный домен без точки+TLD. */
const payload = (n: number) => "a".repeat(n) + "@" + "b".repeat(n) + "!";

/** Безобидное описание ровно на границе отсечки — эталон линейного прохода. */
const benign = "Ровный участок. ".repeat(1_250); // 20 000 символов

const ms = (fn: () => void): number => {
  const t = process.hrtime.bigint();
  fn();
  return Number(process.hrtime.bigint() - t) / 1e6;
};

const median = (xs: number[]): number => xs.slice().sort((a, b) => a - b)[xs.length >> 1];

/** Единица «скорость машины прямо сейчас»: один линейный проход по 20k. */
const calibrate = (): number => ms(() => {
  for (let i = 0; i < 20; i += 1) redactConfidential(benign);
}) / 20;

// АТАКА 26 [HIGH]: стоимость одного вызова ограничена сверху
// | ИНВАРИАНТ: мегабайтная строка-ловушка стоит КОНЕЧНОЕ число линейных проходов
//   по тексту длиной с отсечку — путь записи синхронный и общий для сайта и
//   бота, поэтому важен именно ПОТОЛОК, а не средний случай. До фикса стоимость
//   от длины тела запроса не зависела вообще ничем: 64k занимали минуту, 2 МБ —
//   неограниченно долго, то есть отношение к эталону росло без предела
// | измеряем в единицах эталона, а не в миллисекундах: под параллельным прогоном
//   абсолютное время плавает в разы, отношение — нет (наблюдаемое ~720×)
// | код: backend/src/lib/publishable.ts:163,254-259
test("АТАКА 26: мегабайтная строка-ловушка не подвешивает путь записи", () => {
  const warm = () => void redactConfidential(payload(500));
  warm();
  warm();
  const huge = payload(1_000_000); // строится ВНЕ замера: 2 МБ аллокации шумят
  // эталон снимается по обе стороны от измерения; берём больший — он отражает
  // худшую (самую загруженную) скорость машины и делает порог мягче, не слабее
  const before = calibrate();
  const t = ms(() => void redactConfidential(huge));
  const after = calibrate();
  const unit = Math.max(before, after, 0.001);
  assert.ok(
    t / unit < 4_000,
    `2 МБ ловушки стоят ${(t / unit).toFixed(0)} линейных проходов по 20k ` +
      `(${t.toFixed(0)} мс при эталоне ${unit.toFixed(2)} мс) — потолок потерян`,
  );
});

// АТАКА 26a [HIGH]: рост за отсечкой отсутствует
// | ИНВАРИАНТ: удлинение входа в 50 раз (20k → 1M) не увеличивает время —
//   раньше удвоение давало ~4× (полиномиальный ReDoS) без всякого потолка
// | БЫЛО: по одному замеру на размер, причём строка-ловушка СТРОИЛАСЬ ВНУТРИ
//   замера — аллокация 2 МБ и сборка мусора попадали в результат и в полном
//   (параллельном) прогоне давали случайные выбросы.
//   ИСПРАВЛЕНО 2026-09-01: строки готовятся заранее, замеры идут вперемешку,
//   сравниваются медианы трёх пар
// | код: backend/src/lib/publishable.ts:163,254-259
test("АТАКА 26a: за отсечкой удлинение входа не даёт роста времени", () => {
  const warm = () => void redactConfidential(payload(500));
  warm();
  warm();
  const atCap = payload(20_000);
  const huge = payload(1_000_000);
  const cap: number[] = [];
  const big: number[] = [];
  for (let i = 0; i < 3; i += 1) {
    cap.push(ms(() => void redactConfidential(atCap)));
    big.push(ms(() => void redactConfidential(huge)));
  }
  const growth = median(big) / Math.max(median(cap), 0.001);
  assert.ok(growth < 2.5, `рост ${growth.toFixed(1)}× при удлинении входа в 50 раз`);
});

// АТАКА 26b [MEDIUM]: длина текста на входе ограничена
// | ИНВАРИАНТ: описание длиннее MAX_SCAN_CHARS обрезается ДО регулярок и
//   вызывающий получает об этом предупреждение (описание такой длины — не
//   листинг, а вставленный документ). Нормальное описание не трогается
// | код: backend/src/lib/publishable.ts:163,254-259
test("АТАКА 26b: длина описания на входе ограничивается MAX_SCAN_CHARS", () => {
  const long = "Ровный участок. ".repeat(3_000); // ~48k символов, без ловушки
  const w: string[] = [];
  const out = redactConfidential(long, w);
  assert.equal(out.length, 20_000);
  assert.deepEqual(w, ["описание обрезано до 20000 символов"]);

  // описание нормальной длины проходит целиком и без предупреждений
  const normal = "Ровный участок. ".repeat(50);
  const w2: string[] = [];
  assert.equal(redactConfidential(normal, w2).length, normal.length);
  assert.deepEqual(w2, []);
});

// АТАКА 26c [MEDIUM]: НЕ ЗАКРЫТО — под отсечкой рост всё ещё сверхлинейный,
// но ОГРАНИЧЕН квадратичным потолком
// | ОЖИДАЕТСЯ: санитизация линейна по длине текста
// | ФАКТ: удвоение длины в пределах MAX_SCAN_CHARS даёт ~4× — перебор стартовых
//   позиций остался, катастрофического бэктрекинга больше нет. Под отсечкой это
//   даёт ограниченную сверху стоимость, DoS-примитива не даёт
// | ИНВАРИАНТ, который стережёт тест: рост при удвоении длины остаётся в
//   пределах квадратичного (<8×) — экспонента/квартика означали бы возврат
//   катастрофического бэктрекинга
// | БЫЛО: `t2/t1 > 2` на одиночных замерах 2k/4k — мигало в полном прогоне,
//   потому что параллельные файлы добавляют к КАЖДОМУ замеру аддитивный шум,
//   а он давит на меньший знаменатель сильнее и занижает отношение.
//   ИСПРАВЛЕНО 2026-09-01: замеры вперемешку, по медиане трёх пар, на вчетверо
//   больших телах (4k/8k ≈ 100/410 мс) — шум планировщика на их фоне мал
// | код: backend/src/lib/publishable.ts:151
test("АТАКА 26c: под отсечкой удвоение длины даёт кратно больший, но ограниченный рост", () => {
  const warm = () => void redactConfidential(payload(500));
  warm();
  warm();
  const p4 = payload(4_000);
  const p8 = payload(8_000);
  const short: number[] = [];
  const long: number[] = [];
  for (let i = 0; i < 3; i += 1) {
    short.push(ms(() => void redactConfidential(p4)));
    long.push(ms(() => void redactConfidential(p8)));
  }
  const growth = median(long) / Math.max(median(short), 0.001);
  assert.ok(growth > 1.5, `рост ${growth.toFixed(1)}× — сверхлинейность неожиданно исчезла`);
  assert.ok(growth < 8, `рост ${growth.toFixed(1)}× при удвоении длины — вышли за квадратичный потолок`);
});
