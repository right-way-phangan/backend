/**
 * RED-TEAM РАУНД 2: фикс утечки descriptionRaw принёс ReDoS на путь записи.
 *
 * БЫЛО: раунд 1 поставил redactConfidential() в buildRow. Внутри неё описание
 * построчно прогонялось через CONTACT_LINE_RE, где жила почтовая альтернатива
 * `[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}`: классы по обе стороны от `@`
 * пересекаются по точке, поэтому на строке без валидного домена движок
 * перебирал разбиения квадратично. Длина входа не ограничивалась ничем
 * (DESC_MAX=500 применяется ПОСЛЕ и только при публикации), так что 64 000
 * символов в теле POST /objects занимали event loop серверлесс-функции на
 * минуту → таймаут вместо созданного объекта.
 *
 * ИСПРАВЛЕНО 2026-08-31: почтовый паттерн переписан с ограниченными сверху
 * квантификаторами (`{1,64}@{1,63}(?:\.{1,63}){1,4}`), а вход обрезается до
 * `MAX_SCAN_CHARS = 20 000` с предупреждением. Стоимость вызова теперь
 * ОГРАНИЧЕНА СВЕРХУ независимо от размера тела запроса.
 *
 * 26c остаётся ХАРАКТЕРИЗУЮЩИМ: под отсечкой рост всё ещё сверхлинейный.
 *   npx tsx --test src/lib/adv2-*.test.ts
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { redactConfidential } from "./publishable";

/** Строка-ловушка: длинный локальный кусок, «@», длинный домен без точки+TLD. */
const payload = (n: number) => "a".repeat(n) + "@" + "b".repeat(n) + "!";

const ms = (fn: () => void): number => {
  const t = process.hrtime.bigint();
  fn();
  return Number(process.hrtime.bigint() - t) / 1e6;
};

// АТАКА 26 [HIGH]: стоимость одного вызова ограничена сверху
// | ИНВАРИАНТ: мегабайтная строка-ловушка обрабатывается за то же время, что и
//   строка на границе отсечки — путь записи синхронный и общий для сайта и
//   бота, поэтому важен именно ПОТОЛОК, а не средний случай
// | код: backend/src/lib/publishable.ts:163,254-259
test("АТАКА 26: мегабайтная строка-ловушка не подвешивает путь записи", () => {
  const warm = () => void redactConfidential(payload(500));
  warm();
  warm();
  const t = ms(() => void redactConfidential(payload(1_000_000)));
  assert.ok(t < 5_000, `ожидали <5 с на 2 МБ ловушки, получили ${t.toFixed(0)} мс`);
});

// АТАКА 26a [HIGH]: рост за отсечкой отсутствует
// | ИНВАРИАНТ: удлинение входа в 50 раз (20k → 1M) не увеличивает время —
//   раньше удвоение давало ~4× (полиномиальный ReDoS) без всякого потолка
// | код: backend/src/lib/publishable.ts:163,254-259
test("АТАКА 26a: за отсечкой удлинение входа не даёт роста времени", () => {
  const warm = () => void redactConfidential(payload(500));
  warm();
  warm();
  const tCap = ms(() => void redactConfidential(payload(20_000)));
  const tHuge = ms(() => void redactConfidential(payload(1_000_000)));
  assert.ok(
    tHuge / Math.max(tCap, 0.001) < 2.5,
    `рост ${(tHuge / tCap).toFixed(1)}× при удлинении входа в 50 раз`,
  );
});

// АТАКА 26b [MEDIUM]: длина текста на входе ограничена
// | ИНВАРИАНТ: описание длиннее MAX_SCAN_CHARS обрезается ДО регулярок и
//   вызывающий получает об этом предупреждение (описание такой длины — не
//   листинг, а вставленный документ). Нормальное описание не трогается
// | код: backend/src/lib/publishable.ts:163,254-259
test("АТАКА 26b: длина описания на входе ограничивается MAX_SCAN_CHARS", () => {
  const long = "Ровный участок. ".repeat(3_000); // ~48k символов, без ловушки
  const w: string[] = [];
  const out = redactConfidential(long, w);
  assert.equal(out.length, 20_000);
  assert.deepEqual(w, ["описание обрезано до 20000 символов"]);

  // описание нормальной длины проходит целиком и без предупреждений
  const normal = "Ровный участок. ".repeat(50);
  const w2: string[] = [];
  assert.equal(redactConfidential(normal, w2).length, normal.length);
  assert.deepEqual(w2, []);
});

// АТАКА 26c [MEDIUM]: НЕ ЗАКРЫТО — под отсечкой рост всё ещё сверхлинейный
// | ОЖИДАЕТСЯ: санитизация линейна по длине текста
// | ФАКТ: удвоение длины в пределах MAX_SCAN_CHARS даёт кратно больший рост.
//   Ограниченные квантификаторы убрали катастрофический бэктрекинг, но остался
//   перебор стартовых позиций; DoS-примитив закрыт только потолком отсечки
// | код: backend/src/lib/publishable.ts:151
test("АТАКА 26c: под отсечкой удвоение длины даёт кратно больший рост времени", () => {
  const warm = () => void redactConfidential(payload(500));
  warm();
  warm();
  const t1 = ms(() => void redactConfidential(payload(2_000)));
  const t2 = ms(() => void redactConfidential(payload(4_000)));
  assert.ok(t2 / Math.max(t1, 0.001) > 2, `рост ${(t2 / t1).toFixed(1)}× при удвоении длины`);
});
