/**
 * RED-TEAM РАУНД 3 — DoS-примитив редакции пережил второй цикл фиксов.
 *
 * Раунд 2 нашёл катастрофический бэктрекинг в почтовом паттерне и закрыл его
 * ограниченными квантификаторами + отсечкой MAX_SCAN_CHARS = 20 000. Но самый
 * дорогой шаг — не почтовый паттерн, а REDACT_PRICELIST: у него по обе стороны
 * от альтернативы «расчётный лист | developer price list | прайс-лист» стоит
 * `[^.\n]` со звёздочкой. Ведущая часть заставляет движок перебирать все стартовые позиции внутри
 * абзаца без точек → квадратично по длине абзаца. Отсечка ограничила ПОТОЛОК,
 * но потолок остался высоким: ~1.9 с процессорного времени на один вызов.
 *
 * Вызовов на запрос несколько: createObject прогоняет description и
 * descriptionRaw (2 вызова), updateObject — все три поля TEXT_FIELDS
 * (descriptionRaw + оба ручных описания, 3 вызова). Одно тело PATCH на 60 КБ
 * блокирует event loop серверлесс-функции на секунды.
 *
 * Тесты ЗЕЛЁНЫЕ и характеризующие; ассерты на ОТНОШЕНИЯХ времён, не на
 * абсолютных миллисекундах, поэтому от скорости машины не зависят.
 *   npx tsx --test src/lib/adv3-*.test.ts
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { redactConfidential } from "./publishable";

const ms = (fn: () => void): number => {
  const t = process.hrtime.bigint();
  fn();
  return Number(process.hrtime.bigint() - t) / 1e6;
};
/**
 * Отношение «стоимость одного вызова на большом входе» / «то же на малом».
 * Замеры ЧЕРЕДУЮТСЯ внутри раунда и берётся медиана раундов: файлы node:test
 * идут параллельно, и такое чередование делает ассерт устойчивым к нагрузке —
 * замедление машины бьёт по обоим замерам раунда одинаково. Малый вход
 * прогоняется пачкой, чтобы его замер тоже длился десятки миллисекунд.
 */
const ratio = (big: string, small: string, n: number): number => {
  const rs: number[] = [];
  for (let r = 0; r < 5; r++) {
    const a = ms(() => void redactConfidential(big));
    const b =
      ms(() => {
        for (let i = 0; i < n; i++) redactConfidential(small);
      }) / n;
    rs.push(a / Math.max(b, 1e-6));
  }
  return rs.sort((x, y) => x - y)[2];
};

/** Обычный русский текст листинга БЕЗ точек (одна длинная строка). */
const flat = (n: number) =>
  "Ровный участок с видом на море и подъездной дорогой ".repeat(Math.ceil(n / 51)).slice(0, n);
/** Тот же текст, разбитый на предложения. */
const prose = (n: number) =>
  "Ровный участок. Вид на море. Дорога есть. ".repeat(Math.ceil(n / 42)).slice(0, n);

// АТАКА 69 [HIGH]: стоимость редакции квадратична по длине абзаца без точек
// | ОЖИДАЕТСЯ: санитизация линейна по длине текста — иначе отсечка лишь
//   переносит DoS с «сколько угодно» на «столько, сколько разрешает потолок»
// | ФАКТ: увеличение длины в 4 раза (1k → 4k, обе величины ПОД отсечкой) даёт
//   рост примерно в 16 раз. Виновник — не почтовый паттерн (его раунд 2
//   починил), а ведущая часть `[^.\n]` со звёздочкой в REDACT_PRICELIST
// | код: backend/src/lib/publishable.ts:194-195
test("АТАКА 69: под отсечкой рост стоимости квадратичный (×4 длины → ×16 времени)", () => {
  redactConfidential(flat(1000)); // прогрев JIT
  const r = ratio(flat(4_000), flat(1_000), 16);
  assert.ok(r > 6, `ожидали квадратичный рост, получили ×${r.toFixed(1)}`);
});

// АТАКА 69a [HIGH]: триггер — отсутствие точек, а не «ловушка» в тексте
// | ОЖИДАЕТСЯ: обычное описание объекта обрабатывается за одно и то же время
//   независимо от пунктуации
// | ФАКТ: тот же самый текст той же длины, но разбитый на предложения,
//   обрабатывается в сотни раз быстрее. Значит для атаки не нужен специальный
//   payload: достаточно вставить 20 000 символов одним абзацем в поле описания
//   POST /objects или PATCH /objects/:rw
// | код: backend/src/lib/publishable.ts:194-195
test("АТАКА 69a: текст без точек стоит в сотни раз дороже того же текста с точками", () => {
  redactConfidential(flat(1000));
  const r = ratio(flat(4_000), prose(4_000), 64);
  assert.ok(r > 50, `ожидали разрыв в десятки-сотни раз, получили ×${r.toFixed(1)}`);
});

// АТАКА 69b [MEDIUM]: отсечка применяется К ПОЛЮ, а не к запросу
// | ОЖИДАЕТСЯ: MAX_SCAN_CHARS ограничивает стоимость обработки ОДНОГО запроса
// | ФАКТ: потолок независим для каждого вызова. PATCH с тремя полями
//   TEXT_FIELDS прогоняет через регулярки 3 × 20 000 символов, createObject —
//   2 × 20 000; ограничения на число текстовых полей в теле нет, как нет и
//   ограничения на размер тела
// | код: backend/src/lib/publishable.ts:254-259 + write.ts:711,718-720
test("АТАКА 69b: три поля в одном PATCH дают 3 × MAX_SCAN_CHARS сканирования", () => {
  const field = prose(60_000); // одно поле, втрое длиннее отсечки
  const scanned = [field, field, field].reduce((n, f) => n + redactConfidential(f).length, 0);
  assert.equal(scanned, 60_000); // = 3 × 20 000, по потолку на каждое поле
});
