/**
 * RED-TEAM РАУНД 3 — что сломал/оставил ВТОРОЙ цикл фиксов в редакции контактов.
 *
 * Второй цикл заменил «резать всю строку» на «маскировать найденный контакт
 * пустой строкой» и добавил две эвристики: телефон обязан иметь «+» ИЛИ 9+ цифр
 * подряд, а строка с денежным маркером считается ценой. Обе эвристики дырявые в
 * обе стороны: настоящий тайский телефон проходит насквозь, а обычный английский
 * текст калечится — причём НЕОБРАТИМО, потому что путь записи (buildRow →
 * redactConfidential) сохраняет уже отредактированный текст как оригинал.
 *
 * ИСПРАВЛЕНО 2026-09-01 (третий цикл): добавлены паттерн тайской местной записи
 * телефона (`0XX XXX XXXX`) и паттерн телефонного контекста (tel/phone/тел/моб/
 * call + цифры); ветка мессенджера LINE обзавелась стоп-листом следующих слов,
 * так что «power line runs along the road» больше не калечится. АТАКИ 50, 54,
 * 54a теперь СТЕРЕГУТ фикс.
 *
 * Остальные тесты файла — по-прежнему ХАРАКТЕРИЗУЮЩИЕ (51, 52, 52a, 53, 55):
 * фиксируют фактическое поведение, дыры не закрыты.
 *   npx tsx --test src/lib/adv3-*.test.ts
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { redactConfidential, sanitizeDescription } from "./publishable";

const red = (s: string) => {
  const w: string[] = [];
  return { out: redactConfidential(s, w), warnings: w };
};

// АТАКА 50 [CRITICAL]: тайский телефон в местном формате
// | ИНВАРИАНТ: «084 362 7784» — телефон собственника (ровно так он записан в
//   memory user_phone_numbers и так его диктуют брокеры) — вырезается из
//   описания, которое уходит в публичный payload /objects
// | БЫЛО: правило требовало «+» ИЛИ 9+ цифр ПОДРЯД; разбиение на группы
//   пробелами (национальная запись) не ловилось ни одним из шести паттернов.
//   ИСПРАВЛЕНО 2026-09-01: добавлен паттерн тайской местной записи
//   `0XX XXX XXXX` — ведущий ноль + ровно 10 цифр
// | цена от нуля не начинается, поэтому «8 500 000 THB» новым паттерном не
//   задета — это вторая половина инварианта, без неё фикс съел бы цены
// | код: backend/src/lib/publishable.ts:149-152
test("АТАКА 50: телефон в тайском формате «084 362 7784» вырезается", () => {
  const r = red("Owner Khun Somchai 084 362 7784");
  assert.equal(r.out, "Owner Khun Somchai ");
  assert.deepEqual(r.warnings, ["из описания скрыт контакт/телефон"]);

  // тот же номер без пробелов — ловился и раньше
  assert.equal(red("Owner Khun Somchai 0843627784").out, "Owner Khun Somchai ");

  // и он не доезжает до публикуемого описания
  assert.equal(
    sanitizeDescription("Flat plot near the beach. Owner 084 362 7784", "en", []),
    "Flat plot near the beach. Owner",
  );

  // контроль обратной стороны: сумма с пробелами-разделителями — не телефон
  assert.equal(red("Price 8 500 000 THB").out, "Price 8 500 000 THB");
  assert.equal(red("Asking 12 000 000 THB for 4 rai").out, "Asking 12 000 000 THB for 4 rai");
});

// АТАКА 51 [HIGH]: точка или запятая сразу после номера отключает правило
// | ОЖИДАЕТСЯ: «Owner 0843627784.» — телефон в конце предложения — вырезается
// | ФАКТ: `(?![\d.,])` после \d{9,15} трактует финальную точку как продолжение
//   числа, матч не состоится вовсе. Телефон в конце фразы (самая частая позиция
//   в сообщении собственника) публикуется дословно
// | код: backend/src/lib/publishable.ts:150
test("АТАКА 51: телефон, за которым идёт «.» или «,», не редактируется", () => {
  assert.equal(red("Owner 0843627784.").out, "Owner 0843627784.");
  assert.equal(red("Owner 0843627784, quiet plot").out, "Owner 0843627784, quiet plot");
  assert.equal(red("Собственник 0843627784.").out, "Собственник 0843627784.");

  // тот же номер без хвостовой пунктуации — вырезается
  assert.equal(red("Owner 0843627784").out, "Owner ");
});

// АТАКА 52 [HIGH]: «денежная» эвристика включается от обычных английских слов
// | ОЖИДАЕТСЯ: MONEY_NEAR отличает строку с ценой («8.5M THB») от строки с
//   телефоном
// | ФАКТ: в MONEY_NEAR есть альтернативы `m\b` и `k\b` — они матчат конец
//   ЛЮБОГО слова на «m»/«k»: from, room, warm, walk, park, book. Такая строка
//   объявляется ценой, и чистый цифровой телефон на ней остаётся. Достаточно
//   написать телефон в одной строке со словом «from» — редакции не будет
// | код: backend/src/lib/publishable.ts:160,281
test("АТАКА 52: слова from/room/walk делают строку «денежной» и спасают телефон", () => {
  for (const s of [
    "Call the owner from 9am: 0843627784",
    "Two bedrooms and a big room. Owner 0843627784",
    "Walk to the beach, owner 66843627784",
  ]) {
    assert.equal(red(s).out, s, `строка должна была остаться нетронутой: ${s}`);
  }
  // контроль: та же фраза без слова-ловушки — телефон вырезан
  assert.equal(red("Parking on site, call 0843627784").out, "Parking on site, call ");
});

// АТАКА 52a [MEDIUM]: явная денежная маскировка как способ пронести контакт
// | ОЖИДАЕТСЯ: приписка «THB» рядом с номером не отменяет редакцию
// | ФАКТ: строка объявляется ценой, и любой чисто цифровой матч на ней
//   возвращается как есть — телефон публикуется
// | код: backend/src/lib/publishable.ts:276,281
test("АТАКА 52a: «Owner 66843627784 THB» — денежный маркер отменяет редакцию", () => {
  assert.equal(red("Owner: 66843627784 THB").out, "Owner: 66843627784 THB");
  assert.equal(
    red("Price 8500000 THB. Owner 0843627784").out,
    "Price 8500000 THB. Owner 0843627784",
  );
});

// АТАКА 53 [MEDIUM]: тайские цифры, юникод-дефис и перенос строки
// | ОЖИДАЕТСЯ: номер остаётся номером в любой из записей, принятых в Таиланде
// | ФАКТ: все три формы проходят. `[\d]` — ASCII-цифры, тайские ๐-๙ не
//   покрываются; U+2011 не входит в класс разделителей; редакция построчная,
//   поэтому номер, разорванный переводом строки, не собирается
// | код: backend/src/lib/publishable.ts:149-150,273
test("АТАКА 53: тайские цифры / юникод-дефис / перенос строки обходят правило", () => {
  assert.equal(red("Phone: ๐๘๔ ๓๖๒ ๗๗๘๔").out, "Phone: ๐๘๔ ๓๖๒ ๗๗๘๔");
  assert.equal(red("Call +66‑84‑362‑7784").out, "Call +66‑84‑362‑7784");
  assert.equal(red("Contact +66 84\n362 7784").out, "Contact +66 84\n362 7784");
});

// АТАКА 54 [HIGH]: ложное срабатывание «line» уничтожало смысл описания —
// и делало это на ПУТИ ЗАПИСИ, то есть необратимо
// | ИНВАРИАНТ: «power line» / «electricity line» — характеристика участка
//   (электричество на плацдарме), а не мессенджер LINE; такая строка
//   сохраняется целиком. При этом настоящий контакт в LINE по-прежнему режется
// | БЫЛО: паттерн мессенджера съедал «line» + следующее слово и заменял их
//   пустой строкой; buildRow сохранял результат как descriptionRaw, оригинала в
//   базе не оставалось. ИСПРАВЛЕНО 2026-09-01: мессенджером считается только
//   `line id …` / `line: …` / `line@…` / `line#…` либо `line <ник>`, где ник не
//   из стоп-листа (runs|along|to|from|is|are|at|on|near|and|or|the|…)
// | код: backend/src/lib/publishable.ts:154,283-286
test("АТАКА 54: «power line runs along the road» сохраняется целиком", () => {
  const r = red("Power line runs along the road");
  assert.equal(r.out, "Power line runs along the road");
  assert.deepEqual(r.warnings, []);

  assert.equal(
    red("The plot has a power line and mains water").out,
    "The plot has a power line and mains water",
  );
  assert.equal(red("electricity line to the plot").out, "electricity line to the plot");

  // обратная сторона инварианта: настоящий контакт в LINE всё ещё вырезается
  for (const s of ["LINE somchai88", "LINE: somchai88", "line id somchai88", "line@somchai", "line#somchai"]) {
    const m = red(s);
    assert.equal(m.out, "", `контакт должен был исчезнуть: ${s}`);
    assert.deepEqual(m.warnings, ["из описания скрыт контакт/телефон"]);
  }

  // НЕ ЗАКРЫТО: «Whatsapp available» по-прежнему съедается целиком — у
  // whatsapp-ветки стоп-листа нет, а «available» она принимает за ник
  assert.equal(red("Whatsapp available").out, "");
});

// АТАКА 54a [HIGH]: обе ошибки в одной реалистичной строке листинга
// | ИНВАРИАНТ: текст цел, телефон скрыт — то есть ровно наоборот к тому, что
//   давал второй цикл фиксов (текст калечился, телефон публиковался)
// | БЫЛО: «Flat plot, power along the road. Tel 084 362 7784.».
//   ИСПРАВЛЕНО 2026-09-01: обе половины (стоп-лист «line» + тайский телефон и
//   телефонный контекст «Tel …») сработали в одну сторону
// | точка после вырезанного телефона остаётся — это осознанный след редакции,
//   а не потеря смысла
// | код: backend/src/lib/publishable.ts:149-157
test("АТАКА 54a: одна строка листинга — смысл цел, контакт скрыт", () => {
  assert.equal(
    sanitizeDescription("Flat plot, power line runs along the road. Tel 084 362 7784.", "en", []),
    "Flat plot, power line runs along the road. .",
  );
});

// АТАКА 55 [MEDIUM]: отсечка 20 000 символов режет осмысленное описание молча
// | ОЖИДАЕТСЯ: длинное описание либо сохраняется целиком, либо отклоняется с
//   ошибкой на входе API
// | ФАКТ: redactConfidential обрезает текст и кладёт предупреждение в массив,
//   но buildRow вызывает её БЕЗ массива warnings (значение по умолчанию),
//   а POST /objects warnings вообще не возвращает — обрезанный текст
//   становится единственной версией описания в базе
// | код: backend/src/lib/publishable.ts:254-259 + write.ts:448,519
test("АТАКА 55: описание >20k обрезается, и предупреждение об этом теряется", () => {
  const long = "Ровный участок с видом на море. ".repeat(700); // ~22 400 символов
  const w: string[] = [];
  assert.equal(redactConfidential(long, w).length, 20_000);
  assert.deepEqual(w, ["описание обрезано до 20000 символов"]);

  // вызов без массива warnings (как в buildRow) — обрезка происходит молча
  assert.equal(redactConfidential(long).length, 20_000);
});
